package de.luisgerlinger.backend.boundary.uidto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.annotation.Nullable;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

@Getter
@Setter
@NoArgsConstructor
@Schema(description = "An activity (holiday type) with its packing list")
public class ActivityUiDTO {

    @Schema(description = "Generated by the server, ignored on create and update",
            accessMode = Schema.AccessMode.READ_ONLY)
    @Nullable
    private UUID id;

    @NotBlank
    @Schema(example = "Camping trip")
    private String name;

    @NotNull
    @Valid
    @Schema(description = "The full packing list. On update, entries missing from this list are removed")
    private List<PackedItemUiDTO> packedItems = new ArrayList<>();
}
