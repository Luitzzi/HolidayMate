import { PlusOutlined } from "@ant-design/icons";
import { App, Button, Divider, Select } from "antd";
import { useState } from "react";
import type { CategoryUiDTO } from "../../../generated/interface-api.ts";
import { tokens } from "../../../theme/tokens.ts";
import type { SelectOption } from "../../../components/SelectOption.ts";

type CategorySelectProps = {
  categories: SelectOption<string>[];
  onCreate: (category: CategoryUiDTO) => void;
  isCategoryNameValid: (name: string) => boolean;
  // Injected by Form.Item
  value?: string;
  // Injected by Form.Item
  onChange?: (categoryName: string) => void;
};

export const CategorySelect = ({
  categories,
  onCreate,
  isCategoryNameValid,
  value,
  onChange,
}: CategorySelectProps) => {
  const { message } = App.useApp();
  const [open, setOpen] = useState<boolean>(false);
  const [search, setSearch] = useState("");
  const newName = search.trim();

  /** The id stays empty, it is generated by the database when the activity is saved. */
  const create = () => {
    onCreate({ name: newName });
    onChange?.(newName);
    setSearch("");
    setOpen(false);
  };

  const addCategory = () => {
    if (!isCategoryNameValid(newName)) {
      message.error(`The category name ${newName} is not valid`);
    } else {
      create();
    }
  };

  return (
    <Select
      placeholder="Select or create a category"
      value={value}
      onChange={onChange}
      options={categories}
      open={open}
      onOpenChange={setOpen}
      showSearch={{
        searchValue: search,
        onSearch: setSearch,
        optionFilterProp: "label",
      }}
      popupRender={(menu) => (
        <>
          {menu}
          {
            <>
              <Divider style={{ margin: `${tokens.margin.small} 0` }} />
              <Button
                type="text"
                block
                icon={<PlusOutlined />}
                onClick={addCategory}
              >
                Create "{newName}"
              </Button>
            </>
          }
        </>
      )}
      style={{ width: "100%" }}
    />
  );
};
